drop database if exists foodservice;
create database foodservice;
use foodservice;

-- Customers table
CREATE TABLE Customers (
    customer_id INT PRIMARY KEY,
    customer_name VARCHAR(255),
    customer_email VARCHAR(255),
    customer_phone VARCHAR(20)
);
CREATE TABLE Restaurants (
    restaurant_id INT PRIMARY KEY,
    restaurant_name VARCHAR(255),
    restaurant_address VARCHAR(255),
    restaurant_phone VARCHAR(20)
);

-- Menu Items table
CREATE TABLE MenuItems (
    item_id INT PRIMARY KEY,
    item_name VARCHAR(255),
    item_description TEXT,
    item_price DECIMAL(10,2),
    restaurant_id INT,
    FOREIGN KEY (restaurant_id) REFERENCES Restaurants(restaurant_id)
);
CREATE TABLE DeliveryDrivers (
    driver_id INT PRIMARY KEY,
    driver_name VARCHAR(255),
    driver_phone VARCHAR(20),
    driver_vehicle VARCHAR(255)
);
CREATE TABLE Orders (
    order_id INT PRIMARY KEY,
    order_date DATETIME,
    customer_id INT,
    restaurant_id INT,
    delivery_driver_id INT,
    order_status VARCHAR(50),
    FOREIGN KEY (customer_id) REFERENCES Customers(customer_id),
    FOREIGN KEY (restaurant_id) REFERENCES Restaurants(restaurant_id),
    FOREIGN KEY (delivery_driver_id) REFERENCES DeliveryDrivers(driver_id)
);
CREATE TABLE OrderItems (
    order_item_id INT PRIMARY KEY,
    order_id INT,
    item_id INT,
    quantity INT,
    FOREIGN KEY (order_id) REFERENCES Orders(order_id),
    FOREIGN KEY (item_id) REFERENCES MenuItems(item_id)
);
-- Additional entities

-- Delivery Addresses table (to store customer delivery addresses)
CREATE TABLE DeliveryAddresses (
    address_id INT PRIMARY KEY,
    customer_id INT,
    address_line1 VARCHAR(255),
    address_line2 VARCHAR(255),
    city VARCHAR(100),
    state VARCHAR(100),
    postal_code VARCHAR(20),
    FOREIGN KEY (customer_id) REFERENCES Customers(customer_id)
);

-- Coupons table (to store discount coupons applicable to orders)
CREATE TABLE Coupons (
    coupon_id INT PRIMARY KEY,
    coupon_code VARCHAR(50) UNIQUE,
    discount_amount DECIMAL(10,2),
    expiry_date DATE
);

-- OrdersCoupons table (to associate coupons with orders)
CREATE TABLE OrdersCoupons (
    order_id INT,
    coupon_id INT,
    PRIMARY KEY (order_id, coupon_id),
    FOREIGN KEY (order_id) REFERENCES Orders(order_id),
    FOREIGN KEY (coupon_id) REFERENCES Coupons(coupon_id)
);

-- Ratings table (to store ratings/reviews given by customers to restaurants)
CREATE TABLE Ratings (
    rating_id INT PRIMARY KEY,
    order_id INT,
    restaurant_id INT,
    rating INT,
    review TEXT,
    FOREIGN KEY (order_id) REFERENCES Orders(order_id),
    FOREIGN KEY (restaurant_id) REFERENCES Restaurants(restaurant_id)
);
